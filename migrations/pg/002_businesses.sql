-- 002_businesses.sql — persisted business profiles (Create Business wizard).
--
-- One row per business created through the wizard. The scalar profile fields
-- are real columns; hours / services / contact / social are small nested
-- structures that are only ever read and written whole, so they are JSONB
-- rather than extra tables. Verification documents are intentionally not
-- stored here yet (they need access-controlled storage, not static/uploads).

CREATE TABLE businesses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id BIGINT NOT NULL REFERENCES users(id),
    name TEXT NOT NULL,
    category TEXT NOT NULL,
    location TEXT NOT NULL,
    description TEXT NOT NULL,
    hours JSONB NOT NULL,
    services JSONB NOT NULL DEFAULT '[]'::jsonb,
    contact JSONB NOT NULL DEFAULT '{}'::jsonb,
    social JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX idx_businesses_owner ON businesses (owner_id, id DESC);
