-- A repost is a lightweight pointer from a user to an existing post. No
-- content is copied: the original post stays the single source of truth for
-- text, images, likes and comments. UNIQUE (user_id, post_id) makes a repost
-- idempotent and caps it at one per user per post. Both FKs cascade so a
-- deleted post or user takes its reposts with it (unlike posts.quoted_post_id,
-- there is nothing worth preserving once the original is gone).
CREATE TABLE IF NOT EXISTS reposts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    post_id BIGINT NOT NULL REFERENCES posts(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (user_id, post_id)
);

-- Per-post repost counts and "did the viewer repost these ids" lookups.
CREATE INDEX IF NOT EXISTS idx_reposts_post_id
    ON reposts (post_id);

-- A user's Reposts tab: newest first, keyset-paginated on id.
CREATE INDEX IF NOT EXISTS idx_reposts_user_id_desc
    ON reposts (user_id, id DESC);
