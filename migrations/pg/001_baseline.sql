-- 001_baseline.sql — Postgres-native baseline of Beebo's final SQLite schema.
--
-- Squashes the following SQLite schema sources into a single consolidated
-- Postgres schema (in dependency order):
--
--   * app/db.py init_db()  — inline CREATE TABLE blocks + ad-hoc
--     PRAGMA table_info() ALTERs (users.profile_picture/cover_image/
--     username/bio, comments.parent_comment_id, username backfill)
--   * migrations/001_baseline.sql             — snapshot of init_db() schema
--   * migrations/002_comment_delete_cascade.sql — comments.parent_comment_id
--                                                 ON DELETE CASCADE (table rebuild)
--   * migrations/003_communities.sql          — communities, community_members,
--                                               posts.community_id
--   * migrations/004_comment_images.sql       — comments.image_path
--   * migrations/005_community_images.sql     — communities.icon_image/cover_image
--   * migrations/006_community_notification_level.sql — community_members.notification_level
--   * migrations/007_post_quotes.sql          — posts.quoted_post_id (no FK)
--   * migrations/008_direct_messages.sql      — conversations, messages,
--                                               conversation_reads, conversation_state
--
-- Mapping rules (see docs/PG_AUDIT.md, docs/PG_MIGRATION.md):
--
--   * INTEGER PRIMARY KEY AUTOINCREMENT  -> BIGINT GENERATED BY DEFAULT AS IDENTITY
--   * every FK column                     -> BIGINT
--   * TIMESTAMP DEFAULT CURRENT_TIMESTAMP -> TIMESTAMPTZ DEFAULT now()
--   * TEXT ... DEFAULT (datetime('now'))  -> TIMESTAMPTZ DEFAULT now()
--   * users.username COLLATE NOCASE UNIQUE -> UNIQUE INDEX on lower(username)
--   * community_members.rowid ordering    -> seq BIGINT ... IDENTITY UNIQUE
--
-- Timestamps keep their original NULL/NOT NULL exactly. Only
-- communities.created_at and community_members.joined_at were NOT NULL in
-- SQLite (TEXT NOT NULL DEFAULT (datetime('now'))); all other created_at
-- columns were nullable TIMESTAMP DEFAULT CURRENT_TIMESTAMP.
--
-- Foreign keys keep their exact ON DELETE behavior. A FK listed with no
-- ON DELETE clause is NO ACTION (SQLite's default), matching the source.

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name TEXT NOT NULL,
    email TEXT NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    profile_picture TEXT,
    cover_image TEXT,
    created_at TIMESTAMPTZ DEFAULT now(),
    username TEXT,
    bio TEXT
);

-- Replaces SQLite's UNIQUE INDEX ... ON users(username COLLATE NOCASE).
CREATE UNIQUE INDEX idx_users_username_unique
    ON users (lower(username));

CREATE TABLE communities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug TEXT NOT NULL UNIQUE,
    name TEXT NOT NULL,
    description TEXT NOT NULL,
    topic TEXT NOT NULL,
    type TEXT NOT NULL CHECK (type IN ('public', 'restricted', 'private')),
    icon_emoji TEXT,
    creator_id BIGINT NOT NULL REFERENCES users(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    icon_image TEXT,
    cover_image TEXT
);

CREATE TABLE posts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    content TEXT NOT NULL,
    audience TEXT DEFAULT 'Academic',
    created_at TIMESTAMPTZ DEFAULT now(),
    comment_count INTEGER DEFAULT 0,
    like_count INTEGER DEFAULT 0,
    view_count INTEGER DEFAULT 0,
    community_id BIGINT REFERENCES communities(id),
    -- Intentional: no FK. Preserves quote ids after the original is deleted
    -- (migrations/007_post_quotes.sql); reads serialize a missing target as
    -- an unavailable stub.
    quoted_post_id BIGINT
);

CREATE TABLE post_images (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id BIGINT NOT NULL REFERENCES posts(id) ON DELETE CASCADE,
    image_path TEXT NOT NULL,
    position INTEGER NOT NULL,
    created_at TIMESTAMPTZ DEFAULT now()
);

CREATE TABLE comments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id BIGINT NOT NULL REFERENCES posts(id),
    user_id BIGINT NOT NULL REFERENCES users(id),
    content TEXT NOT NULL,
    created_at TIMESTAMPTZ DEFAULT now(),
    like_count INTEGER DEFAULT 0,
    parent_comment_id BIGINT REFERENCES comments(id) ON DELETE CASCADE,
    image_path TEXT
);

CREATE TABLE likes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    target_type TEXT NOT NULL CHECK (target_type IN ('post', 'comment')),
    -- Intentional: polymorphic reference, no FK (target_id is either a
    -- posts.id or a comments.id depending on target_type).
    target_id BIGINT NOT NULL,
    created_at TIMESTAMPTZ DEFAULT now(),
    UNIQUE (user_id, target_type, target_id)
);

CREATE TABLE dislikes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    comment_id BIGINT NOT NULL REFERENCES comments(id),
    created_at TIMESTAMPTZ DEFAULT now(),
    UNIQUE (user_id, comment_id)
);

CREATE TABLE follows (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    follower_id BIGINT NOT NULL REFERENCES users(id),
    followee_id BIGINT NOT NULL REFERENCES users(id),
    created_at TIMESTAMPTZ DEFAULT now(),
    UNIQUE (follower_id, followee_id)
);

CREATE TABLE highlights (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    title TEXT NOT NULL,
    kind TEXT NOT NULL CHECK (kind IN ('photo', 'video')),
    media_url TEXT NOT NULL,
    created_at TIMESTAMPTZ DEFAULT now()
);

CREATE TABLE search_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    query TEXT NOT NULL,
    created_at TIMESTAMPTZ DEFAULT now()
);

CREATE TABLE library_files (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    title TEXT NOT NULL,
    category TEXT NOT NULL,
    department TEXT,
    course TEXT,
    level TEXT,
    file_path TEXT NOT NULL,
    file_type TEXT NOT NULL,
    file_size INTEGER NOT NULL,
    status TEXT NOT NULL DEFAULT 'approved'
        CHECK (status IN ('pending', 'approved', 'rejected')),
    download_count INTEGER DEFAULT 0,
    created_at TIMESTAMPTZ DEFAULT now()
);

CREATE TABLE credit_transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    amount INTEGER NOT NULL CHECK (amount != 0),
    kind TEXT NOT NULL CHECK (kind IN ('top_up', 'usage', 'free')),
    reason TEXT NOT NULL,
    description TEXT NOT NULL,
    created_at TIMESTAMPTZ DEFAULT now()
);

CREATE TABLE community_members (
    community_id BIGINT NOT NULL REFERENCES communities(id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    role TEXT NOT NULL CHECK (role IN ('creator', 'moderator', 'member')),
    joined_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    notification_level TEXT NOT NULL DEFAULT 'off'
        CHECK (notification_level IN ('off', 'all', 'popular', 'muted')),
    -- Replaces SQLite rowid ordering (community_service orders members by
    -- joined_at DESC/ASC with rowid as a stable tiebreaker; PG has no rowid).
    seq BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    PRIMARY KEY (community_id, user_id)
);

CREATE TABLE conversations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_low_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    user_high_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ DEFAULT now(),
    CHECK (user_low_id < user_high_id),
    UNIQUE (user_low_id, user_high_id)
);

CREATE TABLE messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id BIGINT NOT NULL REFERENCES conversations(id) ON DELETE CASCADE,
    sender_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    body TEXT NOT NULL,
    client_id TEXT,
    created_at TIMESTAMPTZ DEFAULT now(),
    UNIQUE (conversation_id, sender_id, client_id)
);

CREATE TABLE conversation_reads (
    conversation_id BIGINT NOT NULL REFERENCES conversations(id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    last_read_message_id INTEGER NOT NULL DEFAULT 0,
    PRIMARY KEY (conversation_id, user_id)
);

CREATE TABLE conversation_state (
    conversation_id BIGINT PRIMARY KEY REFERENCES conversations(id) ON DELETE CASCADE,
    last_message_id INTEGER NOT NULL DEFAULT 0
);

-- Indexes (definitions preserved, including DESC-ordered composite indexes).

CREATE INDEX idx_follows_followee ON follows (followee_id);
CREATE INDEX idx_highlights_user ON highlights (user_id);
CREATE INDEX idx_posts_user_id ON posts (user_id);
CREATE INDEX idx_posts_created_at ON posts (created_at);
CREATE INDEX idx_posts_user_created ON posts (user_id, created_at DESC, id DESC);
CREATE INDEX idx_posts_community ON posts (community_id, id DESC);
CREATE INDEX idx_posts_quoted_post ON posts (quoted_post_id);
CREATE INDEX idx_comments_post_id ON comments (post_id);
CREATE INDEX idx_likes_target ON likes (target_type, target_id);
CREATE INDEX idx_likes_user_id ON likes (user_id);
CREATE INDEX idx_dislikes_comment_id ON dislikes (comment_id);
CREATE INDEX idx_dislikes_user_id ON dislikes (user_id);
CREATE INDEX idx_search_history_user ON search_history (user_id, created_at DESC);
CREATE INDEX idx_library_files_department ON library_files (department);
CREATE INDEX idx_library_files_category ON library_files (category);
CREATE INDEX idx_library_files_created ON library_files (created_at);
CREATE INDEX idx_library_files_status ON library_files (status);
CREATE INDEX idx_credit_tx_user ON credit_transactions (user_id, id DESC);
CREATE INDEX idx_credit_tx_user_reason ON credit_transactions (user_id, reason, id DESC);
CREATE INDEX idx_community_members_user ON community_members (user_id, joined_at DESC);
CREATE INDEX idx_messages_conversation ON messages (conversation_id, id);
CREATE INDEX idx_conversation_state_last_message ON conversation_state (last_message_id DESC);
